  var KEY = 'mecades_quotes_seen';
  var LABELS = { morning: 'صبح', noon: 'ظهر', afternoon: 'عصر', evening: 'شب', night: 'بامداد' };

  /* ---- بازهٔ روز ---- */
  function part(ts) {
    var h = new Date(ts || Date.now()).getHours();
    if (h >= 5 && h < 11) return 'morning';
    if (h >= 11 && h < 15) return 'noon';
    if (h >= 15 && h < 18) return 'afternoon';
    if (h >= 18 && h < 22) return 'evening';
    return 'night';
  }
  function partLabel(p) { return LABELS[p] || ''; }

  /* ---- کلید ماه شمسی (برای به‌روزرسانی چیدمان ماهانه) ---- */
  function monthKey(ts) {
    var d = new Date(ts || Date.now());
    if (window.Store && window.Store.g2j) {
      var j = window.Store.g2j(d.getFullYear(), d.getMonth() + 1, d.getDate());
      return j[0] + '-' + (j[1] < 10 ? '0' + j[1] : j[1]);
    }
    return d.getFullYear() + '-' + (d.getMonth() + 1);
  }

  /* ---- هش و شانسِ قطعی برای چیدمان ماهانه ---- */
  function hash(str) {
    var h = 2166136261;
    for (var i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; }
    return h >>> 0;
  }
  function rng(seed) {
    var a = seed >>> 0;
    return function () {
      a |= 0; a = (a + 0x6D2B79F5) | 0;
      var t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  /* ---- حافظهٔ جملات دیده‌شده ---- */
  function readSeen() {
    try { var o = JSON.parse(localStorage.getItem(KEY) || '{}'); return (o && typeof o === 'object') ? o : {}; }
    catch (e) { return {}; }
  }
  function writeSeen(o) { try { localStorage.setItem(KEY, JSON.stringify(o)); } catch (e) {} }

  /**
   * انتخاب جملهٔ معروف + نامِ گوینده
   * @param {string} userId  شناسهٔ کاربر (برای جلوگیری از تکرار)
   * @param {number} [ts]    زمان مرجع
   * @returns {{text:string, author:string, part:string, partLabel:string, index:number}}
   */
  function pick(userId, ts) {
    var t = ts || Date.now();
    var key = part(t);
    var list = POOL[key] || POOL.morning;
    var id = userId || 'guest';
    var seen = readSeen();
    var used = seen[id] || {};
    var order = list.map(function (_, i) { return i; });
    var rand = rng(hash(monthKey(t) + '|' + key + '|' + id));
    for (var i = order.length - 1; i > 0; i--) {
      var j = Math.floor(rand() * (i + 1));
      var tmp = order[i]; order[i] = order[j]; order[j] = tmp;
    }
    var idx = order[0], found = false;
    /* جمله‌ای که این کاربر قبلاً ندیده */
    for (var k = 0; k < order.length; k++) {
      var c = order[k];
      if (!used[key + ':' + c]) { idx = c; found = true; break; }
    }
    if (!found) {
      /* همهٔ جملات این بازه دیده شده → حافظه پاک و از نو شروع می‌شود */
      used = {};
    }
    used[key + ':' + idx] = Date.now();
    seen[id] = used;
    writeSeen(seen);
    var q = list[idx];
    return { text: q.t, author: q.a, part: key, partLabel: LABELS[key], index: idx };
  }

  function count() {
    return Object.keys(POOL).reduce(function (a, k) { return a + POOL[k].length; }, 0);
  }
  function all() {
    var out = [];
    Object.keys(POOL).forEach(function (k) {
      POOL[k].forEach(function (q) { out.push(q.t); });
    });
    return out;
  }
  function authors() {
    var out = [];
    Object.keys(POOL).forEach(function (k) {
      POOL[k].forEach(function (q) { out.push(q.a); });
    });
    return out;
  }
  function duplicates() {
    var seen = {}, dup = [];
    all().forEach(function (s) { if (seen[s]) dup.push(s); seen[s] = 1; });
    return dup;
  }

  return {
    pick: pick, part: part, partLabel: partLabel, monthKey: monthKey,
    count: count, all: all, authors: authors, duplicates: duplicates, POOL: POOL
  };
